package com.clicklease.app.service;

import com.clicklease.app.TestFixtures;
import com.clicklease.app.bureau.BureauClient;
import com.clicklease.app.domain.ApplicationStatus;
import com.clicklease.app.domain.LeaseApplication;
import com.clicklease.app.repository.LeaseApplicationRepository;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.test.context.bean.override.mockito.MockitoBean;

import java.math.BigDecimal;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertTrue;
import static org.mockito.ArgumentMatchers.anyString;
import static org.mockito.Mockito.when;

/**
 * Submission paths not covered by the real-HTTP ITs: declined decisions are
 * persisted with score + reason, and a missing/blank idempotency key gets an
 * auto-generated one.
 */
@SpringBootTest
class SubmissionDecisionIT {

    @Autowired
    private ApplicationService applicationService;

    @Autowired
    private LeaseApplicationRepository repository;

    @MockitoBean
    private BureauClient bureauClient;

    @Test
    void declinedSubmissionPersistsScoreAndReason() {
        when(bureauClient.fetchScore(anyString())).thenReturn(649);
        var form = TestFixtures.validForm();
        form.setAmount(new BigDecimal("40000")); // >25k needs >=700 -> decline

        LeaseApplication application = applicationService.submit(form);

        assertEquals(ApplicationStatus.DECLINED, application.getStatus());
        assertEquals(649, application.getCreditScore());
        assertNotNull(application.getDecisionReason());
        assertTrue(repository.findById(application.getId()).isPresent());
    }

    @Test
    void blankIdempotencyKeyGetsAutoGenerated() {
        when(bureauClient.fetchScore(anyString())).thenReturn(700);
        var form = TestFixtures.validForm();
        form.setIdempotencyKey("   ");

        LeaseApplication application = applicationService.submit(form);

        assertNotNull(application.getIdempotencyKey());
        assertFalse(application.getIdempotencyKey().isBlank());
        assertTrue(repository.findByIdempotencyKey(application.getIdempotencyKey()).isPresent());
    }

    @Test
    void missingIdempotencyKeyGetsAutoGenerated() {
        when(bureauClient.fetchScore(anyString())).thenReturn(700);
        var form = TestFixtures.validForm();
        form.setIdempotencyKey(null);

        LeaseApplication application = applicationService.submit(form);

        assertNotNull(application.getIdempotencyKey());
        assertTrue(repository.findByIdempotencyKey(application.getIdempotencyKey()).isPresent());
    }
}
